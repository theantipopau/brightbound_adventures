/// Skill practice screen for numeracy skills
class NumeracyPracticeScreen extends StatefulWidget {
  final Skill skill;
  final Color themeColor;
  final String? zoneId;
  final String? zoneName;

  const NumeracyPracticeScreen({
    super.key,
    required this.skill,
    required this.themeColor,
    this.zoneId,
    this.zoneName,
  });

  @override
  State<NumeracyPracticeScreen> createState() => _NumeracyPracticeScreenState();
}

class _NumeracyPracticeScreenState extends State<NumeracyPracticeScreen> {
  /// The three beats of one quest session: intro → activity → results.
  bool _intro = true;
  bool _showResults = false;
  int _correctAnswers = 0;
  int _totalQuestions = 0;
  double _accuracy = 0;
  int _hintsUsed = 0;

  /// Questions are generated once per session: generating them during build
  /// produced a fresh random set on every rebuild, which could swap the
  /// questions under a child mid-quest (and made the session untestable).
  late List<NumeracyQuestion> _questions;

  /// Stable identity for the current completion. Generated once per session
  /// so the reward transaction can be replayed without re-awarding, and
  /// regenerated by "Play again" so the next session earns its own rewards.
  late String _sessionId;

  @override
  void initState() {
    super.initState();
    _startSessionIdentity();
    _questions = _getQuestionsForSkill();
  }

  void _startSessionIdentity() {
    _sessionId = '${widget.skill.id}_${DateTime.now().microsecondsSinceEpoch}';
  }

  List<NumeracyQuestion> _getQuestionsForSkill() {
    // Get adaptive difficulty level
    final adaptiveDifficulty = context.read<AdaptiveDifficultyService>();
    final difficulty =
        adaptiveDifficulty.getDifficultyForSkill(widget.skill.id);

    switch (widget.skill.id) {
      case 'skill_counting':
      case 'skill_number_recognition':
        return CountingQuestions.getByDifficulty(difficulty);
      case 'skill_addition':
        return AdditionQuestions.getByDifficulty(difficulty);
      case 'skill_subtraction':
        return SubtractionQuestions.getByDifficulty(difficulty);
      case 'skill_multiplication':
        return MultiplicationQuestions.getByDifficulty(difficulty);
      case 'skill_patterns':
        return PatternQuestions.getByDifficulty(difficulty);
      case 'skill_place_value':
        return PlaceValueQuestions.getByDifficulty(difficulty);
      default:
        // Return generic questions for skills without specific question banks
        return _getGenericQuestions();
    }
  }

  List<NumeracyQuestion> _getGenericQuestions() {
    // Use question generator for skills without specific banks
    final adaptiveDifficulty = context.read<AdaptiveDifficultyService>();
    final difficulty =
        adaptiveDifficulty.getDifficultyForSkill(widget.skill.id);

    try {
      return NumberNebulaQuestionGenerator.generate(
        skill: widget.skill.name,
        difficulty: difficulty,
        count: 10,
      );
    } catch (e) {
      // Generator failure is an empty state, not a fake quest: the honest
      // "no questions ready" screen below replaces it (no bait questions).
      return const <NumeracyQuestion>[];
    }
  }

  void _onGameComplete(double accuracy, int correct, int total, int hintsUsed) {
    // Daily-challenge tracking lives here because it is goal bookkeeping
    // rather than a reward award; XP, stars, streaks and achievement unlocks
    // all flow through RewardTransactionService in the results screen.
    try {
      final dailyService = context.read<DailyChallengeService>();
      for (int i = 0; i < correct; i++) {
        for (final challenge in dailyService.todaysChallenges) {
          if (challenge.skillId == widget.skill.id) {
            dailyService.updateProgress(
              challengeId: challenge.id,
              correct: true,
            );
            break;
          }
        }
      }
    } catch (_) {
      // Daily challenge service not available (embedded demos/tests).
    }

    setState(() {
      _showResults = true;
      _accuracy = accuracy;
      _correctAnswers = correct;
      _totalQuestions = total;
      _hintsUsed = hintsUsed;
    });
  }

  void _playAgain() {
    _startSessionIdentity();
    setState(() {
      _intro = true;
      _showResults = false;
      _correctAnswers = 0;
      _totalQuestions = 0;
      _accuracy = 0;
      _hintsUsed = 0;
      _questions = _getQuestionsForSkill();
    });
  }

  void _exitToZone() {
    Navigator.of(context).pop();
  }

  @override
  Widget build(BuildContext context) {
    if (_showResults) {
      return NumeracyResultsScreen(
        skillName: widget.skill.name,
        skillId: widget.skill.id,
        sessionId: _sessionId,
        correctAnswers: _correctAnswers,
        totalQuestions: _totalQuestions,
        accuracy: _accuracy,
        hintsUsed: _hintsUsed,
        themeColor: widget.themeColor,
        onPlayAgain: _playAgain,
        onExit: _exitToZone,
        zoneId: widget.zoneId,
        zoneName: widget.zoneName,
      );
    }

    final questions = _questions;

    if (questions.isEmpty) {
      // Honest empty state: no fake questions, no placeholder bait. Shown
      // before the briefing — there is nothing to start yet.
      return Scaffold(
        appBar: AppBar(
          title: Text(widget.skill.name),
          backgroundColor: widget.themeColor,
        ),
        body: Center(
          child: Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              const Text('🌌', style: TextStyle(fontSize: 64)),
              const SizedBox(height: 16),
              Text(
                'No questions are ready for ${widget.skill.name} yet.',
                style: Theme.of(context).textTheme.titleLarge,
                textAlign: TextAlign.center,
              ),
              const SizedBox(height: 8),
              Text(
                'We\'re preparing new challenges for ${widget.skill.name} — '
                'pick another quest from ${widget.zoneName ?? 'the zone'} '
                'for now.',
                style: Theme.of(context).textTheme.bodyMedium?.copyWith(
                      color: Colors.grey[600],
                    ),
                textAlign: TextAlign.center,
              ),
              const SizedBox(height: 24),
              BrandedBackButton(
                label: 'Back to Zone',
                onPressed: () => Navigator.pop(context),
                backgroundColor: widget.themeColor,
                foregroundColor: InkTokens.on(widget.themeColor),
                borderColor: widget.themeColor.withValues(alpha: 0.85),
                tokenBackgroundColor: Colors.white.withValues(alpha: 0.16),
              ),
            ],
          ),
        ),
      );
    }

    if (_intro) {
      return Scaffold(
        backgroundColor: Theme.of(context).colorScheme.surface,
        body: ZoneQuestIntro(
          zoneId: widget.zoneId,
          zoneName: widget.zoneName,
          title: widget.skill.name,
          objective:
              'Practise ${widget.skill.name}: ${widget.skill.description}.',
          questionCount: questions.length,
          accent: widget.themeColor,
          difficulty: widget.skill.difficulty,
          naplanLabel: widget.skill.naplanAreaLabel,
          onBack: _exitToZone,
          onStart: () => setState(() => _intro = false),
        ),
      );
    }

    return NumeracyGame(
      questions: questions,
      skillName: widget.skill.name,
      themeColor: widget.themeColor,
      onComplete: _onGameComplete,
      onCancel: _exitToZone,
    );
  }
}
