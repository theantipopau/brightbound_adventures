/// Main screen for Story Springs skill practice
/// Routes to appropriate story game based on skill selected
class StoryPracticeScreen extends StatefulWidget {
  final String skillId;
  final String skillName;
  final String? zoneId;
  final String? zoneName;

  const StoryPracticeScreen({
    super.key,
    required this.skillId,
    required this.skillName,
    this.zoneId,
    this.zoneName,
  });

  @override
  State<StoryPracticeScreen> createState() => _StoryPracticeScreenState();
}

class _StoryPracticeScreenState extends State<StoryPracticeScreen> {
  /// The three beats of one quest session: intro → activity → results.
  bool _intro = true;
  bool _showResults = false;
  int _correctAnswers = 0;
  int _totalQuestions = 0;
  int _hintsUsed = 0;
  QuestSessionSummary? _history;

  /// Stable identity for the current completion. Generated once per session
  /// so the reward transaction can be replayed without re-awarding, and
  /// regenerated by "Try Again" so the next session earns its own rewards.
  late String _sessionId;

  /// When this session's questions were dealt — recorded in the history
  /// entry so spaced repetition and review recommendations see real timing.
  late DateTime _sessionStartedAt;

  /// Questions are generated once per session: generating them during build
  /// produced a fresh random set on every rebuild, which could swap the
  /// questions under a child mid-quest (and made the session untestable).
  late List<StoryQuestion> _questions;

  @override
  void initState() {
    super.initState();
    _startSessionIdentity();
    AiQuestionService.instance.prefetch(
      zone: 'story_springs',
      skill: widget.skillId,
      difficulty: 3,
      fetchCount: 10,
      ageGroup: '6-12',
    );
  }

  void _startSessionIdentity() {
    _sessionId = '${widget.skillId}_${DateTime.now().microsecondsSinceEpoch}';
    _sessionStartedAt = DateTime.now();
    _questions = _getQuestionsForSkill();
  }

  List<StoryQuestion> _getQuestionsForSkill() {
    // Get adaptive difficulty level
    final adaptiveDifficulty = context.read<AdaptiveDifficultyService>();
    final difficulty = adaptiveDifficulty.getDifficultyForSkill(widget.skillId);

    try {
      // Use generator for varied questions based on skill
      return StorySpringsQuestionGenerator.generate(
        skill: widget.skillId,
        difficulty: difficulty,
        count: 10,
      );
    } catch (e) {
      // Fallback to hardcoded questions if generator fails
      switch (widget.skillId) {
        case 'skill_story_sequencing':
          return StorySequencingQuestions.getByDifficulty(difficulty);
        case 'skill_emotion_recognition':
          return EmotionRecognitionQuestions.getByDifficulty(difficulty);
        case 'skill_descriptive_language':
          return DescriptiveLanguageQuestions.getByDifficulty(difficulty);
        case 'skill_dialogue_creation':
          return DialogueCreationQuestions.getByDifficulty(difficulty);
        case 'skill_plot_structure':
          return PlotStructureQuestions.getByDifficulty(difficulty);
        case 'skill_character_development':
          return CharacterDevelopmentQuestions.getByDifficulty(difficulty);
        default:
          return StorySequencingQuestions.getByDifficulty(difficulty);
      }
    }
  }

  String _getSkillDescription() {
    switch (widget.skillId) {
      case 'skill_story_sequencing':
        return 'Put story events in the right order!';
      case 'skill_emotion_recognition':
        return 'Identify how characters feel!';
      case 'skill_descriptive_language':
        return 'Use vivid words to paint pictures!';
      case 'skill_dialogue_creation':
        return 'Write character conversations!';
      case 'skill_plot_structure':
        return 'Build stories with beginning, middle, end!';
      case 'skill_character_development':
        return 'Create memorable characters!';
      case 'skill_dialogue_punctuation':
        return 'Punctuate dialogue correctly!';
      case 'skill_voice_recording':
        return 'Tell stories with your voice!';
      default:
        return 'Practice your storytelling skills!';
    }
  }

  void _onGameFinish(int correct, int total, int hintsUsed) {
    // Daily-challenge tracking lives here because it is goal bookkeeping
    // rather than a reward award; XP, stars, streaks and achievement unlocks
    // all flow through RewardTransactionService in the results screen.
    try {
      final dailyService = context.read<DailyChallengeService>();
      for (int i = 0; i < correct; i++) {
        for (final challenge in dailyService.todaysChallenges) {
          if (challenge.skillId == widget.skillId) {
            dailyService.updateProgress(
              challengeId: challenge.id,
              correct: true,
            );
            break;
          }
        }
      }
    } catch (_) {
      // Daily challenge service not available (embedded demos/tests).
    }

    // The story game has no session recorder of its own, so this screen
    // supplies the history entry the recommendation engine reads. Its id
    // derives from the clock at finish, so a reward retry replaces rather
    // than duplicates it.
    final endedAt = DateTime.now();
    final history = QuestSessionSummary(
      id: '${endedAt.microsecondsSinceEpoch}_${widget.skillId}',
      zoneId: 'story-springs',
      skillId: widget.skillId,
      skillName: widget.skillName,
      mode: 'practice',
      startedAt: _sessionStartedAt,
      endedAt: endedAt,
      totalQuestions: total,
      correctAnswers: correct,
      score: correct * 10,
      hintsUsed: hintsUsed,
      difficulty:
          context.read<AdaptiveDifficultyService>().getDifficultyForSkill(
                widget.skillId,
              ),
      forced: false,
      questionIds: _questions.map((question) => question.id).toList(),
    );

    setState(() {
      _correctAnswers = correct;
      _totalQuestions = total;
      _hintsUsed = hintsUsed;
      _history = history;
      _showResults = true;
    });
  }

  void _onContinue() {
    Navigator.of(context).pop();
  }

  void _onRetry() {
    _startSessionIdentity();
    setState(() {
      _intro = true;
      _showResults = false;
      _correctAnswers = 0;
      _totalQuestions = 0;
      _hintsUsed = 0;
      _history = null;
    });
  }

  @override
  Widget build(BuildContext context) {
    if (_showResults) {
      return StoryResultsScreen(
        correctAnswers: _correctAnswers,
        totalQuestions: _totalQuestions,
        skillName: widget.skillName,
        sessionId: _sessionId,
        skillId: widget.skillId,
        zoneId: widget.zoneId,
        zoneName: widget.zoneName,
        history: _history,
        hintsUsed: _hintsUsed,
        onContinue: _onContinue,
        onRetry: _onRetry,
      );
    }

    if (_questions.isEmpty) {
      return _buildEmptyStateScreen();
    }

    if (_intro) {
      final skill = findZoneSkill(context, widget.zoneId, widget.skillId);
      return Scaffold(
        backgroundColor: Theme.of(context).colorScheme.surface,
        body: ZoneQuestIntro(
          zoneId: widget.zoneId,
          zoneName: widget.zoneName,
          title: widget.skillName,
          objective: 'Practise ${widget.skillName}: '
              '${skill?.description ?? _getSkillDescription()}',
          questionCount: _questions.length,
          accent: WorldTokens.fromZoneId(widget.zoneId ?? 'story_springs')
              .primaryColor,
          difficulty: skill?.difficulty,
          naplanLabel: skill?.naplanAreaLabel,
          onBack: _onContinue,
          onStart: () => setState(() => _intro = false),
        ),
      );
    }

    return StoryGame(
      questions: _questions,
      skillName: widget.skillName,
      onComplete: () {},
      onFinish: _onGameFinish,
    );
  }

  Widget _buildEmptyStateScreen() {
    // Honest empty state: the generator always returns a bank today, but if
    // it ever fails the child must see a real "nothing to play" screen,
    // not a promise of something arriving later.
    return Scaffold(
      body: Container(
        decoration: const BoxDecoration(
          gradient: LinearGradient(
            begin: Alignment.topCenter,
            end: Alignment.bottomCenter,
            colors: [
              Color(0xFF1a1a2e),
              Color(0xFF16213e),
            ],
          ),
        ),
        child: SafeArea(
          child: Center(
            child: Column(
              mainAxisAlignment: MainAxisAlignment.center,
              children: [
                const Text('📚', style: TextStyle(fontSize: 80)),
                const SizedBox(height: 24),
                Text(
                  widget.skillName,
                  style: const TextStyle(
                    color: Colors.white,
                    fontSize: 28,
                    fontWeight: FontWeight.bold,
                  ),
                ),
                const SizedBox(height: 12),
                Text(
                  _getSkillDescription(),
                  style: const TextStyle(
                    color: Colors.white60,
                    fontSize: 16,
                  ),
                  textAlign: TextAlign.center,
                ),
                const SizedBox(height: 32),
                Container(
                  padding:
                      const EdgeInsets.symmetric(horizontal: 24, vertical: 12),
                  decoration: BoxDecoration(
                    color: Colors.purple.withValues(alpha: 0.3),
                    borderRadius: BorderRadius.circular(20),
                    border: Border.all(color: Colors.purple.shade300),
                  ),
                  child: const Text(
                    'No questions ready yet',
                    style: TextStyle(
                      color: Colors.white,
                      fontSize: 18,
                      fontWeight: FontWeight.bold,
                    ),
                  ),
                ),
                const SizedBox(height: 48),
                SizedBox(
                  width: 220,
                  child: BrandedBackButton(
                    label: 'Back to Zone',
                    onPressed: () => Navigator.of(context).pop(),
                    backgroundColor: Colors.white.withValues(alpha: 0.08),
                    foregroundColor: Colors.white,
                    borderColor: Colors.purple.shade300.withValues(alpha: 0.7),
                    tokenBackgroundColor: Colors.purple.withValues(alpha: 0.24),
                  ),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }
}
