/// Main screen for Adventure Arena motor skills practice
/// Routes to appropriate motor game based on skill selected
class MotorPracticeScreen extends StatefulWidget {
  final String skillId;
  final String skillName;
  final String? zoneId;
  final String? zoneName;

  const MotorPracticeScreen({
    super.key,
    required this.skillId,
    required this.skillName,
    this.zoneId,
    this.zoneName,
  });

  @override
  State<MotorPracticeScreen> createState() => _MotorPracticeScreenState();
}

class _MotorPracticeScreenState extends State<MotorPracticeScreen> {
  /// The three beats of one quest session: intro → activity → results.
  bool _intro = true;
  bool _showResults = false;

  /// The round config is dealt once per session: regenerating it during
  /// build would reset the round under a child mid-activity (the same
  /// rebuild bug the other zones fixed by generating once per session).
  late MotorGameConfig _config;
  MotorGameResult? _gameResult;
  QuestSessionSummary? _history;

  /// Stable identity for the current completion. Generated once per session
  /// so the reward transaction can be replayed without re-awarding, and
  /// regenerated by "Play Again" so the next session earns its own rewards.
  late String _sessionId;

  /// When this session's round was dealt — recorded in the history entry so
  /// review recommendations see real timing.
  late DateTime _sessionStartedAt;

  @override
  void initState() {
    super.initState();
    _startSessionIdentity();
  }

  void _startSessionIdentity() {
    _sessionId = '${widget.skillId}_${DateTime.now().microsecondsSinceEpoch}';
    _sessionStartedAt = DateTime.now();
    final adaptiveDifficulty = context.read<AdaptiveDifficultyService>();
    _config = AdventureArenaGenerator.generate(
      skill: widget.skillId,
      difficulty: adaptiveDifficulty.getDifficultyForSkill(widget.skillId),
    );
  }

  void _onGameComplete(MotorGameResult result) {
    // The motor game has no session recorder of its own, so this screen
    // supplies the history entry the recommendation engine reads. Its id
    // derives from the clock at completion, so a reward retry replaces
    // rather than duplicates it. Targets (not questions) are the units, so
    // there are no question ids to list.
    final endedAt = DateTime.now();
    final history = QuestSessionSummary(
      id: '${endedAt.microsecondsSinceEpoch}_${widget.skillId}',
      zoneId: 'adventure-arena',
      skillId: widget.skillId,
      skillName: widget.skillName,
      mode: 'practice',
      startedAt: _sessionStartedAt,
      endedAt: endedAt,
      totalQuestions: result.totalTargets,
      correctAnswers: result.targetsHit,
      score: result.score,
      hintsUsed: 0,
      difficulty:
          context.read<AdaptiveDifficultyService>().getDifficultyForSkill(
                widget.skillId,
              ),
      forced: false,
      questionIds: const [],
    );

    setState(() {
      _gameResult = result;
      _history = history;
      _showResults = true;
    });
  }

  void _onContinue() {
    Navigator.of(context).pop();
  }

  void _onRetry() {
    _startSessionIdentity();
    setState(() {
      _intro = true;
      _showResults = false;
      _gameResult = null;
      _history = null;
    });
  }

  @override
  Widget build(BuildContext context) {
    if (_showResults && _gameResult != null) {
      return MotorResultsScreen(
        targetsHit: _gameResult!.targetsHit,
        totalTargets: _gameResult!.totalTargets,
        score: _gameResult!.score,
        avgReactionTime: _gameResult!.averageReactionTime,
        accuracy: _gameResult!.accuracy,
        skillName: widget.skillName,
        sessionId: _sessionId,
        skillId: widget.skillId,
        zoneId: widget.zoneId,
        zoneName: widget.zoneName,
        history: _history,
        onContinue: _onContinue,
        onRetry: _onRetry,
      );
    }

    if (_intro) {
      final skill = findZoneSkill(context, widget.zoneId, widget.skillId);
      return Scaffold(
        backgroundColor: Theme.of(context).colorScheme.surface,
        body: ZoneQuestIntro(
          zoneId: widget.zoneId ?? 'adventure_arena',
          zoneName: widget.zoneName,
          title: widget.skillName,
          objective: skill == null
              ? 'Practise ${widget.skillName}.'
              : 'Practise ${widget.skillName}: ${skill.description}.',
          questionCount: _config.rounds,
          accent: WorldTokens.fromZoneId(
            widget.zoneId ?? 'adventure_arena',
          ).primaryColor,
          difficulty: skill?.difficulty,
          naplanLabel: skill?.naplanAreaLabel,
          onBack: _onContinue,
          onStart: () => setState(() => _intro = false),
        ),
      );
    }

    return MotorGame(
      config: _config,
      onGameComplete: _onGameComplete,
    );
  }
}
