/// The three beats of one quest session: intro → activity → results.
enum QuestPhase { intro, playing, results }

/// Skill practice screen that connects skills to their games.
///
/// Owns the session loop for the literacy/creative zone: a quest
/// introduction, the learning encounter, and the reward reveal. Rewards
/// themselves are applied exactly once by `RewardTransactionService` inside
/// the results screen — this screen deliberately never touches XP, stars or
/// streaks.
class SkillPracticeScreen extends StatefulWidget {
  final Skill skill;
  final Color themeColor;
  final String? zoneId;
  final String? zoneName;

  const SkillPracticeScreen({
    super.key,
    required this.skill,
    required this.themeColor,
    this.zoneId,
    this.zoneName,
  });

  @override
  State<SkillPracticeScreen> createState() => _SkillPracticeScreenState();
}

class _SkillPracticeScreenState extends State<SkillPracticeScreen> {
  QuestPhase _phase = QuestPhase.intro;
  int _correctAnswers = 0;
  int _totalQuestions = 0;
  double _accuracy = 0;
  int _hintsUsed = 0;
  String? _guardianMessage;
  String? _guardianEmoji;

  late final List<LiteracyQuestion> _questions;

  /// Stable identity for the current completion. Generated once per session
  /// so the reward transaction can be replayed without re-awarding, and
  /// regenerated by "Play again" so the next session earns its own rewards.
  late String _sessionId;

  @override
  void initState() {
    super.initState();
    _startSessionIdentity();
    // Questions are generated once per session: generating them during build
    // produced a fresh random set on every rebuild, which could swap the
    // questions under a child mid-quest (and made the session untestable).
    _questions = _getQuestionsForSkill();
    AiQuestionService.instance.prefetch(
      zone: SkillProvider.normalizeZoneId(widget.zoneId ?? 'word_woods'),
      skill: widget.skill.id,
      difficulty: widget.skill.difficulty,
      fetchCount: 10,
      ageGroup: '6-12',
    );
  }

  void _startSessionIdentity() {
    _sessionId = '${widget.skill.id}_${DateTime.now().microsecondsSinceEpoch}';
  }

  List<LiteracyQuestion> _getQuestionsForSkill() {
    switch (widget.skill.id) {
      case 'skill_homophones':
        return HomophoneQuestions.getByDifficulty(widget.skill.difficulty);
      case 'skill_apostrophes':
        return ApostropheQuestions.getByDifficulty(widget.skill.difficulty);
      case 'skill_comma_usage':
        return PunctuationQuestions.getByDifficulty(widget.skill.difficulty);
      // Creative Corner skills
      case 'skill_visual_arts':
      case 'skill_music':
      case 'skill_art_elements':
      case 'skill_creative_expression':
      case 'skill_famous_artists':
        return CreativeCornerQuestions.getBySkillId(
          widget.skill.id,
          difficulty: widget.skill.difficulty,
        );
      default:
        return _getGeneratedQuestions();
    }
  }

  /// Procedural questions for skills without a hand-authored bank. The
  /// generator has bounded inputs and deterministic-per-seed output; the
  /// empty state below is the honest fallback if it ever returns nothing.
  List<LiteracyQuestion> _getGeneratedQuestions() {
    try {
      return WordWoodsQuestionGenerator.generate(
        skill: widget.skill.name,
        difficulty: widget.skill.difficulty,
        count: 10,
      );
    } catch (_) {
      return const <LiteracyQuestion>[];
    }
  }

  ZoneData get _zone {
    final normalized = (widget.zoneId ?? 'word_woods').replaceAll('_', '-');
    for (final zone in ZoneCatalog.zones) {
      if (zone.id == normalized) return zone;
    }
    return ZoneCatalog.zones.first;
  }

  String get _zoneLabel => widget.zoneName ?? _zone.name;

  /// Zone label for the intro chip: zone routes already arrive as
  /// "🌲 Word Woods", catalogue-derived ones need their emoji adding.
  String get _zonePill {
    final label = _zoneLabel;
    if (label.contains(_zone.name)) return label;
    return '${_zone.emoji} $label';
  }

  QuestRecommendation get _recommendation {
    final skills = context.read<SkillProvider>().getZoneSkills(_zone.id);
    final history = context.read<QuestSessionHistoryService>();
    final spaced = context.read<SpacedRepetitionService>();
    return const RecommendationService().recommend(
      zoneId: _zone.id,
      zoneName: _zone.name,
      zoneSkills: skills,
      recentSessions: history.recentSessions(limit: 40),
      dueSkillIds: spaced.dueSkillIds.toSet(),
      justCompletedSkillId: widget.skill.id,
    );
  }

  String get _questObjective =>
      'Practise ${widget.skill.name}: ${widget.skill.description}.';

  String get _questReason {
    final recommendation = _recommendation;
    if (recommendation.skillId == widget.skill.id) {
      return recommendation.childReason;
    }
    return 'Strengthen ${widget.skill.name} and light up more of '
        '$_zoneLabel.';
  }

  void _onGameComplete(double accuracy, int correct, int total) {
    // Daily-challenge tracking lives here because it is goal bookkeeping
    // rather than a reward award; XP, stars, streaks and achievement unlocks
    // all flow through RewardTransactionService in the results screen.
    try {
      final dailyService = context.read<DailyChallengeService>();
      for (int i = 0; i < correct; i++) {
        for (final challenge in dailyService.todaysChallenges) {
          if (challenge.skillId == widget.skill.id) {
            dailyService.updateProgress(
              challengeId: challenge.id,
              correct: true,
            );
            break;
          }
        }
      }
    } catch (_) {
      // Daily challenge service not available (embedded demos/tests).
    }

    setState(() {
      _phase = QuestPhase.results;
      _accuracy = accuracy;
      _correctAnswers = correct;
      _totalQuestions = total;
      final guardian = guardianForZone(widget.zoneId ?? '');
      if (guardian != null) {
        _guardianMessage = guardian.skillCompleteMessage(correct);
        _guardianEmoji = guardian.emoji;
      }
    });
  }

  void _playAgain() {
    _startSessionIdentity();
    setState(() {
      _phase = QuestPhase.intro;
      _correctAnswers = 0;
      _totalQuestions = 0;
      _accuracy = 0;
      _hintsUsed = 0;
      _guardianMessage = null;
      _guardianEmoji = null;
    });
  }

  void _exitToZone() {
    Navigator.of(context).pop();
  }

  @override
  Widget build(BuildContext context) {
    if (_phase == QuestPhase.results) {
      return QuizResultsScreen(
        skillName: widget.skill.name,
        skillId: widget.skill.id,
        sessionId: _sessionId,
        correctAnswers: _correctAnswers,
        totalQuestions: _totalQuestions,
        accuracy: _accuracy,
        hintsUsed: _hintsUsed,
        themeColor: widget.themeColor,
        onPlayAgain: _playAgain,
        onExit: _exitToZone,
        guardianMessage: _guardianMessage,
        guardianEmoji: _guardianEmoji,
        zoneId: _zone.id,
        zoneName: _zoneLabel,
      );
    }

    if (_phase == QuestPhase.intro) {
      final guardian = guardianForZone(widget.zoneId ?? '');
      return Scaffold(
        backgroundColor: Theme.of(context).colorScheme.surface,
        body: QuestIntro(
          zoneLabel: _zonePill,
          title: widget.skill.name,
          objective: _questObjective,
          reason: _questReason,
          questionCount: _questions.isEmpty ? 0 : _questions.length,
          rewardXp: 135,
          rewardStars: 3,
          accent: widget.themeColor,
          companionEmoji: guardian?.emoji,
          companionLine: guardian?.questHook,
          difficulty: widget.skill.difficulty,
          naplanLabel: widget.skill.naplanAreaLabel,
          onBack: _exitToZone,
          onStart: () => setState(() => _phase = QuestPhase.playing),
        ),
      );
    }

    if (_questions.isEmpty) {
      // Honest empty state: no fake questions, no placeholder bait.
      return Scaffold(
        // Single-back empty state: the explicit "Back to Zone" button
        // below is the only back action (AppBar chevron removed).
        appBar: AppBar(
          title: Text(widget.skill.name),
          backgroundColor: widget.themeColor,
          automaticallyImplyLeading: false,
          centerTitle: true,
        ),
        body: Center(
          child: Padding(
            padding: const EdgeInsets.all(24),
            child: Column(
              mainAxisAlignment: MainAxisAlignment.center,
              children: [
                const Icon(Icons.auto_stories_rounded,
                    size: 64, color: Colors.grey),
                const SizedBox(height: 16),
                Text(
                  'No questions are ready for ${widget.skill.name} yet.',
                  textAlign: TextAlign.center,
                  style: Theme.of(context).textTheme.titleLarge,
                ),
                const SizedBox(height: 8),
                Text(
                  'Pick another quest from $_zoneLabel — there are plenty '
                  'more to explore.',
                  textAlign: TextAlign.center,
                  style: Theme.of(context).textTheme.bodyMedium,
                ),
                const SizedBox(height: 24),
                ElevatedButton(
                  onPressed: _exitToZone,
                  child: const Text('Back to Zone'),
                ),
              ],
            ),
          ),
        ),
      );
    }

    return MultipleChoiceGame(
      questions: _questions,
      skillName: widget.skill.name,
      themeColor: widget.themeColor,
      naplanLabel: widget.skill.naplanAreaLabel,
      onComplete: _onGameComplete,
      onCancel: _exitToZone,
    );
  }
}
